function createRemoteRun(remoteHost, matlabVersion)

    % BaseTools.createRemoteRun - Generates a remote execution script.
    %
    % Run this function from any project folder to create a local,
    % context-aware version of the remote execution script. By default, the
    % remote machine is assumed to be 'atlas', running Matlab2026a, but
    % this can be overridden with appropriate arguments. The result is a
    % bash script such as 'atlas_run.sh'. Running that script will update
    % the remote machine with any recent file changes and then will execute
    % the 'batch_main.m' script. Results are stored on the remote machine
    % and must be copied back to your local machine via ssh or using SMB or
    % equivalent.
    
    if nargin < 1 || isempty(remoteHost), remoteHost = 'atlas'; end
    if nargin < 2 || isempty(matlabVersion), matlabVersion = 'R2026a'; end

    % 1. CONTEXT DISCOVERY (Local MATLAB side)
    localDir = pwd;
    [~, folderName] = fileparts(localDir);
    
    % Detection: Research style (inside Matlab/) vs GitHub style (Project Root)
    if strcmpi(folderName, 'Matlab')
        projectRoot = fileparts(localDir);
    else
        projectRoot = localDir;
    end
    [~, projectName] = fileparts(projectRoot);

    scriptName = sprintf('%s_run.sh', remoteHost);
    
    % 2. BASH TEMPLATE
    % Note: We use \$HOME inside the heredoc so it evaluates on the Remote Host,
    % but we use $HOME (unescaped) for the Local side logic.
    genTime = char( datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss') );   
    
    bashTemplate = sprintf([...
        '#!/bin/bash\n', ...
        '# Generated by BaseTools.createRemoteRun on ' genTime '\n', ...
        '# Executing this script will copy updated files to the remote machine and then execute batch_main.m\n\n', ...
        '# --- 1. CONFIGURATION ---\n', ...
        'REMOTE_HOST="' remoteHost '" \n', ...
        'MATLAB_APP="/Applications/MATLAB_' matlabVersion '.app/bin/matlab"\n\n', ...
        '# Use $HOME to ensure portability across different local users\n', ...
        'LOCAL_LIB_ROOT="$HOME/Documents/GitHub/"\n', ...
        '# Determine script location so it can be run from anywhere\n', ...
        'LOCAL_SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)\n', ...
        'PROJECT_NAME="' projectName '"\n\n', ...
        '# Remote paths\n', ...
        'REMOTE_HOME=$(ssh "$REMOTE_HOST" "echo \\$HOME")\n', ...
        'REMOTE_GITHUB_ROOT="$REMOTE_HOME/Documents/GitHub"\n', ...
        'REMOTE_RESEARCH_ROOT="$REMOTE_HOME/Documents/Research"\n', ...
        'REMOTE_PROJECT_PATH="$REMOTE_RESEARCH_ROOT/$PROJECT_NAME"\n', ...
        '# We always execute from a Matlab/ subfolder on the remote for consistency\n', ...
        'REMOTE_EXEC_DIR="$REMOTE_PROJECT_PATH/Matlab"\n', ...
        'PID_FILE="$REMOTE_EXEC_DIR/matlab.pid"\n\n', ...
        '# --- 2. HELPERS ---\n', ...
        'function log_section() {\n', ...
        '    printf "\\n\\n==========================================================\\n"\n', ...
        '    printf ">>> %%s\\n" "$1"\n', ...
        '    printf "==========================================================\\n"\n', ...
        '}\n\n', ...
        '# --- 3. SPECIAL COMMANDS (stop / status / watch) ---\n', ...
        'if [ "$1" == "stop" ]; then\n', ...
        '    log_section "Stopping MATLAB on $REMOTE_HOST"\n', ...
        '    ssh "$REMOTE_HOST" << EOF\n', ...
        '        if [ -f "$PID_FILE" ]; then\n', ...
        '            TARGET_PID=\\$(cat "$PID_FILE")\n', ...
        '            PGID=\\$(ps -o pgid -p \\$TARGET_PID | tail -n 1 | tr -d " ")\n', ...
        '            if [ ! -z "\\$PGID" ]; then\n', ...
        '                echo "Killing Process Group \\$PGID..."\n', ...
        '                kill -TERM -\\$PGID 2>/dev/null || kill -9 -\\$PGID 2>/dev/null\n', ...
        '            fi\n', ...
        '            rm "$PID_FILE"\n', ...
        '        fi\n', ...
        '        pkill -u \\$(whoami) -f MATLAB\n', ...
        '        echo "Cleanup complete."\n', ...
        'EOF\n', ...
        '    exit 0\n', ...
        'fi\n\n', ...
        'if [ "$1" == "status" ]; then\n', ...
        '    log_section "Snapshot of Atlas Output"\n', ...
        '    ssh "$REMOTE_HOST" "tail -n 20 \\\"$REMOTE_EXEC_DIR/batch_output.log\\\" | tr -cd ''\\11\\12\\15\\40-\\176''"\n', ...
        '    log_section "Process Resources"\n', ...
        '    # Clean column output for Mac Studio\n', ...
        '    ssh "$REMOTE_HOST" "ps -cxo pid,pcpu,pmem,state,comm | grep -i MATLAB | grep -v grep || echo ''No MATLAB processes found.''"\n', ...
        '    printf "\\nSentinel Status:\\n"\n', ...
        '    ssh "$REMOTE_HOST" "ls -lh \\\"$REMOTE_EXEC_DIR/JOB_FINISHED.mat\\\" 2>/dev/null || echo ''No Sentinel found.''"\n', ...
        '    exit 0\n', ...
        'fi\n\n', ...
        'if [ "$1" == "watch" ]; then\n', ...
        '    log_section "Streaming Atlas Output (Ctrl+C to stop)"\n', ...
        '    ssh "$REMOTE_HOST" "tail -f \\"$REMOTE_EXEC_DIR/batch_output.log\\""\n', ...
        '    exit 0\n', ...
        'fi\n\n', ...
        '# --- 4. DEPLOYMENT ---\n', ...
        '# Ensure remote directories exist before rsync\n', ...
        'ssh "$REMOTE_HOST" "mkdir -p \\\"$REMOTE_EXEC_DIR\\\" \\\"$REMOTE_PROJECT_PATH/Data\\\" \\\"$REMOTE_PROJECT_PATH/Figures\\\""\n\n', ...
        '# Check if MATLAB is already running (Verify PID + Process Name + Sentinel State)\n', ...
        'EXISTING_PID=$(ssh "$REMOTE_HOST" "cat \\\"$PID_FILE\\\" 2>/dev/null")\n', ...
        'if [ ! -z "$EXISTING_PID" ]; then\n', ...
        '    # Check if PID is alive AND is actually a MATLAB process\n', ...
        '    if ssh "$REMOTE_HOST" "ps -p $EXISTING_PID -o comm= 2>/dev/null | grep -qi MATLAB"; then\n', ...
        '        # It is running, but did it technically finish? (Sentinel check)\n', ...
        '        if ssh "$REMOTE_HOST" "[ ! -f \\\"$REMOTE_EXEC_DIR/JOB_FINISHED.mat\\\" ]"; then\n', ...
        '            printf "\\nERROR: MATLAB is already running (PID: $EXISTING_PID).\\n"\n', ...
        '            printf "Run ''./' scriptName ' stop'' to clear it.\\n\\n"\n', ...
        '            exit 1\n', ...
        '        else\n', ...
        '            # Sentinel exists; previous run is done, these are just "ghost" processes\n', ...
        '            ssh "$REMOTE_HOST" "pkill -u \\$(whoami) -f MATLAB; rm \\\"$PID_FILE\\\""\n', ...
        '        fi\n', ...
        '    else\n', ...
        '        # PID is dead or not MATLAB; clear stale file\n', ...
        '        ssh "$REMOTE_HOST" "rm \\\"$PID_FILE\\\""\n', ...
        '    fi\n', ...
    'fi\n\n', ...
        'log_section "Syncing Libraries to $REMOTE_HOST"\n', ...
        'rsync -avzL --delete --exclude ''.git/'' --exclude ''.gitignore'' --exclude ''.DS_Store'' "$LOCAL_LIB_ROOT" "$REMOTE_HOST":"\\"$REMOTE_GITHUB_ROOT/\\""\n\n', ...
        'log_section "Syncing Project Code: $PROJECT_NAME"\n', ...
        'rsync -avzL --delete \\\n', ...
        '    --exclude ''.git/'' --exclude ''Archive/'' --exclude ''.DS_Store'' \\\n', ...
        '    --exclude ''Data/'' --exclude ''Figures/'' \\\n', ...
        '    --exclude ''batch_output.log'' --exclude ''matlab.pid'' --exclude ''JOB_FINISHED.mat'' \\\n', ...
        '    "$LOCAL_SCRIPT_DIR/" "$REMOTE_HOST":"\\"$REMOTE_EXEC_DIR/\\""\n\n', ...
        'log_section "Launching Job on $REMOTE_HOST"\n', ...
        'ssh "$REMOTE_HOST" << EOF\n', ...
        '    rm -f "$REMOTE_EXEC_DIR/JOB_FINISHED.mat"\n', ...
        '    export HEMINGWAY_LAB_ROOT="$REMOTE_GITHUB_ROOT"\n', ...
        '    cd "$REMOTE_EXEC_DIR"\n', ...
        '    # Double-background with full redirection to ensure SSH exits immediately\n', ...
        '    ( ( nohup bash -c "($MATLAB_APP -batch ''setup; batch_main; exit''; rm -f \\\"$PID_FILE\\\"; pkill -u \\$(whoami) -f MATLAB)" > batch_output.log 2>&1 & ) >/dev/null 2>&1 < /dev/null )\n', ...
        '    sleep 1\n', ...
        '    # Use ps to find the actual MATLAB PID just started\n', ...
        '    NEW_PID=\\$(ps -cxo pid,comm | grep -i MATLAB | head -n 1 | awk ''{print \\$1}'')\n', ...
        '    echo "\\$NEW_PID" > "$PID_FILE"\n', ...
        '    echo "Job submitted! PID: \\$NEW_PID"\n', ...
        '    echo "Use ./' scriptName ' watch to check in."\n', ...
        'EOF\n' ...
    ]);

    % 3. WRITE & SET PERMISSIONS
    fid = fopen(scriptName, 'w');
    fprintf(fid, '%s', bashTemplate);
    fclose(fid);
    [status, ~] = system(['chmod +x ', scriptName]);
    
    if status == 0
        fprintf('Created %s for project: %s\n', scriptName, projectName);
    else
        fprintf('Created %s, but failed to set executable permissions.\n', scriptName);
    end
end